"""SQLAlchemy models for every RADAR table.

One model per table in the schema (docs/architecture/data-model.md and the
implementation plan): alerts, incidents, investigation_plans, recommendations,
feedback, outbox_events, processed_events, runbook_documents, audit_log.

Column types, lengths, nullability, server defaults, foreign keys, and index
names mirror the DDL exactly so the Alembic autogenerated migration matches the
intended schema. UUID primary keys default to ``gen_random_uuid()`` and
timestamps to ``now()`` on the database side; ``updated_at`` columns are set
explicitly by the application (matching the plan), not by a trigger.
"""

# NOTE: no ``from __future__ import annotations`` here. SQLAlchemy declarative
# reads the ``Mapped[...]`` annotations at mapper-configuration time; stringized
# annotations force it down a de-stringify path that is broken for ``X | None``
# unions on Python 3.14 + SQLAlchemy 2.0.36. Real annotations avoid it.

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    PrimaryKeyConstraint,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

_GEN_UUID = "gen_random_uuid()"


class Base(DeclarativeBase):
    """Declarative base for all RADAR tables."""


class Alert(Base):
    __tablename__ = "alerts"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text(_GEN_UUID)
    )
    source: Mapped[str] = mapped_column(String(64), nullable=False)
    source_alert_id: Mapped[str | None] = mapped_column(String(256))
    fingerprint: Mapped[str] = mapped_column(String(64), nullable=False)
    service_name: Mapped[str] = mapped_column(String(128), nullable=False)
    alert_name: Mapped[str] = mapped_column(String(256), nullable=False)
    severity: Mapped[str] = mapped_column(String(32), nullable=False)
    status: Mapped[str] = mapped_column(
        String(32), nullable=False, server_default=text("'firing'")
    )
    raw_payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    labels: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, server_default=text("'{}'::jsonb")
    )
    annotations: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, server_default=text("'{}'::jsonb")
    )
    fired_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    received_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    incident_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("incidents.id", deferrable=True, initially="DEFERRED"),
    )
    correlation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), nullable=False
    )

    __table_args__ = (
        Index("idx_alerts_fingerprint", "fingerprint"),
        Index("idx_alerts_incident_id", "incident_id"),
        Index("idx_alerts_service_name", "service_name"),
        Index("idx_alerts_fired_at", text("fired_at DESC")),
        Index("idx_alerts_status", "status"),
        Index("idx_alerts_correlation_id", "correlation_id"),
    )


