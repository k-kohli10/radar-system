class ProcessedEvent(Base):
    __tablename__ = "processed_events"

    event_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True))
    processed_by: Mapped[str] = mapped_column(String(64), nullable=False)
    processed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # Composite PK: the same event_id can be independently marked processed by
    # each service, matching is_already_processed's (event_id, processed_by)
    # lookup. The PK index also serves that lookup, so no separate index needed.
    __table_args__ = (
        PrimaryKeyConstraint("event_id", "processed_by", name="pk_processed_events"),
    )


